CREATE TABLE Estação
(
  ID INT NOT NULL,
  Localização VARCHAR (255) NOT NULL,
  Data_ DATE NOT NULL,
  PRIMARY KEY (ID)
);

CREATE TABLE Tipo_de_Estação
(
  Móvel VARCHAR (255) NOT NULL,
  Permanente VARCHAR (255) NOT NULL,
  IDTE INT NOT NULL,
  ID INT NOT NULL,
  PRIMARY KEY (IDTE),
  FOREIGN KEY (ID) REFERENCES Estação(ID)
);

CREATE TABLE Tipo_de_Sensor
(
  Ar VARCHAR (255) NOT NULL,
  Solo VARCHAR (255) NOT NULL,
  Água VARCHAR (255) NOT NULL,
  IDTS INT NOT NULL,
  PRIMARY KEY (IDTS)
);

CREATE TABLE Sensores_de_Radiação
(
  Limite_Máximo FLOAT NOT NULL,
  Limite_Mínimo FLOAT NOT NULL,
  IDS INT NOT NULL,
  ID INT NOT NULL,
  IDTS INT NOT NULL,
  PRIMARY KEY (IDS),
  FOREIGN KEY (ID) REFERENCES Estação(ID),
  FOREIGN KEY (IDTS) REFERENCES Tipo_de_Sensor(IDTS)
);



