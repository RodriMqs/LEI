CREATE TABLE FORNECEDOR
(
  CODIGO INT NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  ENDEREÇO VARCHAR(50) NOT NULL,
  TELEFONE INT NOT NULL,
  TELEX INT NOT NULL,
  PRIMARY KEY (CODIGO)
);

CREATE TABLE TRANSPORTE
(
  NAVIO VARCHAR(50) NOT NULL,
  NÚMERO INT NOT NULL,
  PRIMARY KEY (NÚMERO)
);

CREATE TABLE CONTRATO
(
  PRAZO INT NOT NULL,
  VALOR INT NOT NULL,
  MOEDA CHAR(3) NOT NULL,
  DATA DATE NOT NULL,
  NUMERO INT NOT NULL,
  CODIGO INT NOT NULL,
  NÚMERO INT NOT NULL,
  PRIMARY KEY (NUMERO),
  FOREIGN KEY (CODIGO) REFERENCES FORNECEDOR(CODIGO),
  FOREIGN KEY (NÚMERO) REFERENCES TRANSPORTE(NÚMERO)
);

CREATE TABLE MERCADORIA
(
  UNIDADE_MEDIDA CHAR(3) NOT NULL,
  CÓDIGO INT NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  PRIMARY KEY (CÓDIGO)
);

CREATE TABLE COMPRADA
(
  QUANTIDADE INT NOT NULL,
  PREÇO_UNITÁRIO FLOAT NOT NULL,
  CÓDIGO INT NOT NULL,
  NUMERO INT NOT NULL,
  PRIMARY KEY (CÓDIGO, NUMERO),
  FOREIGN KEY (CÓDIGO) REFERENCES MERCADORIA(CÓDIGO),
  FOREIGN KEY (NUMERO) REFERENCES CONTRATO(NUMERO)
);