CREATE TABLE PROFESSOR
(
  NUM_PROFESSOR INT IDENTITY(1,1) NOT NULL
	CONSTRAINT PK_PROFESSOR PRIMARY KEY,
  NOME VARCHAR(100) NOT NULL,

  EMAIL NVARCHAR(150) NULL
	CONSTRAINT CK_PROFESSOR_EMAIL
	CHECK(EMAIL LIKE '%_@_%._%'),
  
  SALARIO DECIMAL(10, 2) NOT NULL
	CONSTRAINT CK_PROFESSOR_SALARIO
	CHECK (SALARIO >= 960),
  
  TELEFONE VARCHAR(20) NOT NULL
	CONSTRAINT UQ_PROFESSOR_TELEFONE UNIQUE
	CONSTRAINT CK_PROFESSOR_TELEFONE
	CHECK(TELEFONE LIKE '20[0-9][0-9][0-9][0-9][0-9]'),
  
  GABINETE VARCHAR(20) NOT NULL,
  ID_DEPARTAMENTO INT NOT NULL,
);

CREATE TABLE DEPARTAMENTO
(
  ID_DEPARTAMENTO INT NOT NULL,
  NOME_DEPARTAMENTO VARCHAR(100) NOT NULL,
  ID_CHEFE INT NOT NULL,
  PRIMARY KEY (ID_DEPARTAMENTO),
  UNIQUE (ID_CHEFE),
  FOREIGN KEY (ID_CHEFE) REFERENCES PROFESSOR(NUM_PROFESSOR)
);


ALTER TABLE PROFESSOR
  ADD CONSTRAINT FK_PROFESSOR_DEPARTAMENTO
  FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES DEPARTAMENTO(ID_DEPARTAMENTO);

CREATE TABLE CURSO
(
  COD_CURSO INT NOT NULL,
  NOME VARCHAR(100) NOT NULL,
  DATA_INI DATE NOT NULL,
  DATA_FIM DATE NOT NULL,
  SALA VARCHAR(20) NOT NULL,
  ID_DEPARTAMENTO INT NOT NULL,
  NUM_PROFESSOR INT NOT NULL,
  PRIMARY KEY (COD_CURSO),
  FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES DEPARTAMENTO(ID_DEPARTAMENTO),
  FOREIGN KEY (NUM_PROFESSOR) REFERENCES PROFESSOR(NUM_PROFESSOR)
);

CREATE TABLE ESTUDANTE
(
  NUM_ESTUDANTE INT IDENTITY(1,1) 
	CONSTRAINT PK_NUM_ESTUDANTE PRIMARY KEY,
 
  NUMERO CHAR(7) NOT NULL   
	CONSTRAINT UQ_ESTUDANTE_NUMERO UNIQUE
	CONSTRAINT CK_ESTUDANTE_NUMERO
	CHECK(NUMERO LIKE '20[0-9][0-9][0-9][0-9][0-9]') ,
  
  NOME VARCHAR(100) NOT NULL,
  
  EMAIL NVARCHAR(150) NULL
	CONSTRAINT CK_ESTUDANTE_EMAIL 
	CHECK (EMAIL LIKE '%_@_%._%'),
  
  DATA_NASC DATE NOT NULL,
  DATA_INSC DATE NOT NULL
	CONSTRAINT DF_ESTUDANTE_DATA_INSCRICAO
	DEFAULT(CAST(GETDATE() AS DATE)),
	CONSTRAINT CK_ESTUDANTE_IDADE
	CHECK(DATA_NASC <= DATEADD(YEAR, -16, DATA_INSC)),
  
  COD_CURSO INT NULL
	CONSTRAINT FK_ESTUDANTE_COD_CURSO
	FOREIGN KEY (COD_CURSO)
	REFERENCES CURSO (COD_CURSO) ON DELETE SET NULL,
  
  ENDERECO VARCHAR(200) NOT NULL,
);

CREATE TABLE DISCIPLINA
(
	COD_DISCIPLINA INT IDENTITY (1,1)
		CONSTRAINT PK_CO_DISCIPLINA PRIMARY KEY,
	NOME_DISCIPLINA VARCHAR(1000) NOT NULL,

	HORAS INT NOT NULL
		CONSTRAINT CK_DISCIPLINA_HORAS
		CHECK(HORAS>0),
	
	NOME_PROFESSOR VARCHAR(100) NOT NULL
		CONSTRAINT FK_DISCIPLINA_PROFESSOR
		FOREIGN KEY (NOME_PROFESSOR)
		REFERENCES PROFESSOR(NOME),


	COD_CURSO INT NOT NULL
		CONSTRAINT FK_DISCIPLINA_CURSO
		FOREIGN KEY (COD_CURSO)
		REFERENCES CURSO(COD_CURSO),
)

CREATE TABLE FREQUENTA
(
  COD_CURSO INT NOT NULL,
  NUM_ESTUDANTE INT NOT NULL,
  CLASSIFICACAO DECIMAL(4, 2) NOT NULL
	CONSTRAINT CK_FREQUENTA_CLASSIFICACAO
	CHECK (CLASSIFICACAO BETWEEN 0 AND 20),
  PRIMARY KEY (COD_CURSO, NUM_ESTUDANTE),
  FOREIGN KEY (COD_CURSO) REFERENCES CURSO(COD_CURSO),
  FOREIGN KEY (NUM_ESTUDANTE) REFERENCES ESTUDANTE(NUM_ESTUDANTE)
);

CREATE TABLE CONCORRER
(
  COD_CURSO_1 INT NOT NULL,
  COD_CURSO_2 INT NOT NULL,
  PRIMARY KEY (COD_CURSO_1, COD_CURSO_2),
  FOREIGN KEY (COD_CURSO_1) REFERENCES CURSO(COD_CURSO),
  FOREIGN KEY (COD_CURSO_2) REFERENCES CURSO(COD_CURSO)
);