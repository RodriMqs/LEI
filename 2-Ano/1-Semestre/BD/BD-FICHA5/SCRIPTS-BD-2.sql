CREATE TABLE ZONA
(
  CODIGO INT NOT NULL,
  DESIGNACAO INT NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  PRIMARY KEY (CODIGO)
);

CREATE TABLE BALCAO
(
  NUMERO INT NOT NULL,
  DESIGNACAO INT NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  ENDERECO VARCHAR(50) NOT NULL,
  CODIGO INT NOT NULL,
  PRIMARY KEY (NUMERO),
  FOREIGN KEY (CODIGO) REFERENCES ZONA(CODIGO)
);

CREATE TABLE CONTA
(
  NQU INT NOT NULL,
  TIPO CHAR(5) NOT NULL,
  SALDO FLOAT NOT NULL,
  LIMITEC FLOAT NOT NULL,
  NUMERO INT NOT NULL,
  PRIMARY KEY (NQU),
  FOREIGN KEY (NUMERO) REFERENCES BALCAO(NUMERO)
);

CREATE TABLE CLIENTE
(
  CODIGO INT NOT NULL,
  NOME VARCHAR(50) NOT NULL,
  TIPO CHAR(5) NOT NULL,
  ENDERECO VARCHAR(50) NOT NULL,
  PRIMARY KEY (CODIGO)
);

CREATE TABLE TITULAR
(
  CODIGO INT NOT NULL,
  NQU INT NOT NULL,
  PRIMARY KEY (CODIGO, NQU),
  FOREIGN KEY (CODIGO) REFERENCES CLIENTE(CODIGO),
  FOREIGN KEY (NQU) REFERENCES CONTA(NQU)
);